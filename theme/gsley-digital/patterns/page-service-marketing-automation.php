<details class="wp-block-details" open><summary>How is this different from Email Marketing?</summary>
<!-- wp:paragraph -->
<p>Email is one channel. Marketing Automation is the orchestration layer above all channels — email, SMS, ads, in-product — running on a unified customer record. Many clients start with the Email Sprint and graduate here when the lifecycle outgrows a single channel.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>And how is it different from Automation &amp; RevOps?</summary>
<!-- wp:paragraph -->
<p>This is marketing-owned, customer-facing lifecycle orchestration. <a href="/services/digital/automation-and-revops/" style="text-decoration:underline">Automation &amp; RevOps</a> in the Digital pillar is the back-office, revenue-operations counterpart. They share a data philosophy and are often deployed together.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do we need to change platforms?</summary>
<!-- wp:paragraph -->
<p>Usually not. The Diagnose phase works with what you have wherever possible; the value is in the data model and orchestration logic, not the vendor. If a platform genuinely can't support the design, we'll say so and explain why.</p>
